  panFileUrl: '',
  aadhaarFileUrl: '',
  passportFileUrl: '',
  bankName: '',
  accountHolderName: '',
  accountNumber: '',
  ifscCode: '',
  branchName: '',
  accountType: 'Savings',
  bloodGroup: 'B+',
