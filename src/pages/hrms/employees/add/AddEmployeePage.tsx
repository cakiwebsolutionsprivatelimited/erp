import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import { useForm, FormProvider } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { useAppSelector, useAppDispatch } from '@/store';
import { setActiveTab, resetOnboardingState, addTimelineEvent } from '@/store/features/employeeOnboardingSlice';

import { employeeOnboardingSchema } from './schemas/employee.schema';
import { type EmployeeFormData } from './types/employee.types';
import { useEmployeeDraft } from './hooks/useEmployeeDraft';
import { useEmployeeAutoSave } from './hooks/useEmployeeAutoSave';
import { useEmployeeValidation } from './hooks/useEmployeeValidation';
import { employeeService } from './services/employee.service';

import { AddEmployeeHeader } from './components/header/AddEmployeeHeader';
import { TabNavigation, TABS_LIST } from './components/tabs/TabNavigation';
import { notify } from '@/services/notificationService';

// Lazy-rendering tab sections
import { PersonalDetailsSection } from './components/sections/PersonalDetailsSection';
import { EmploymentDetailsSection } from './components/sections/EmploymentDetailsSection';
import { ContactAddressSection } from './components/sections/ContactAddressSection';
import { FamilyInformationSection } from './components/sections/FamilyInformationSection';
import { EducationSection } from './components/sections/EducationSection';
import { WorkExperienceSection } from './components/sections/WorkExperienceSection';
import { SkillsCertificationsSection } from './components/sections/SkillsCertificationsSection';
import { DocumentsKycSection } from './components/sections/DocumentsKycSection';
import { BankPayrollSection } from './components/sections/BankPayrollSection';
import { MedicalInformationSection } from './components/sections/MedicalInformationSection';
import { SystemAccessSection } from './components/sections/SystemAccessSection';
import { SalaryStructureSection } from './components/sections/SalaryStructureSection';
import { StatutorySection } from './components/sections/StatutorySection';
import { AssetsJoiningKitSection } from './components/sections/AssetsJoiningKitSection';
import { NotesAttachmentsSection } from './components/sections/NotesAttachmentsSection';
import { ReviewSubmitSection } from './components/review/ReviewSubmitSection';

// Dialog/Confirmation components from shadcn
import { Dialog, DialogContent, DialogHeader, DialogTitle, DialogDescription, DialogFooter } from '@/components/ui/dialog';
import { Button } from '@/components/ui/button';
import { ArrowLeft, ArrowRight, ShieldCheck, Check } from 'lucide-react';

